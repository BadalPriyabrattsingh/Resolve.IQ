// Lazy initialized Gemini client
let geminiClient: GoogleGenAI | null = null;

function getGeminiClient(): GoogleGenAI | null {
  if (geminiClient) return geminiClient;
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
    return null;
  }
  try {
    geminiClient = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
    return geminiClient;
  } catch (err) {
    console.warn('Failed to initialize GoogleGenAI client:', err);
    return null;
  }
}

/**
 * Helper to call Gemini with timeout and fallback model on transient 503 high demand
 */
async function callGeminiWithFallback(
  ai: GoogleGenAI,
  req: {
    contents: string;
    config: any;
    timeoutMs?: number;
  }
) {
  const modelsToTry = ['gemini-3.8-flash', 'gemini-3.1-pro-preview'];
  let lastError: any = null;

  for (const model of modelsToTry) {
    try {
      const timeoutPromise = new Promise<never>((_, reject) =>
        setTimeout(() => reject(new Error(`Gemini API timeout (${model})`)), req.timeoutMs || 5000)
      );

      const response = (await Promise.race([
        ai.models.generateContent({
          model,
          contents: req.contents,
          config: req.config,
        }),
        timeoutPromise,
      ])) as any;

      if (response?.text) {
        return response;
      }
    } catch (err: any) {
      lastError = err;
      const isUnavailable =
        err?.status === 503 ||
        String(err?.message || '').includes('503') ||
        String(err?.message || '').includes('UNAVAILABLE') ||
        String(err?.message || '').includes('high demand');
      if (isUnavailable) {
        // Try fallback model
        continue;
      }
      throw err;
    }
  }
  throw lastError;
}

/**
 * Generate a comprehensive investigation using Gemini or deterministic evidence synthesis
 */
export async function runInvestigationAnalysis(
  incident: Incident,
  evidenceList: Evidence[],
  timelineList: TimelineEvent[]
): Promise<Investigation> {
  const client = getGeminiClient();

  // If Gemini API is configured, attempt model generation
  if (client) {
    try {
      const generated = await analyzeWithGemini(client, incident, evidenceList, timelineList);
      if (generated) {
        return generated;
      }
    } catch (err: any) {
      const isHighDemand =
        err?.status === 503 ||
        String(err?.message || '').includes('503') ||
        String(err?.message || '').includes('high demand') ||
        String(err?.message || '').includes('UNAVAILABLE');
      if (isHighDemand) {
        console.log('[ResolveIQ SRE Copilot] Model at peak demand, smoothly switching to deterministic evidence synthesis.');
      } else {
        console.warn('Gemini analysis unavailable, using deterministic evidence synthesis:', err?.message || err);
      }
    }
  }

  // Deterministic synthesis based on actual evidence
  return synthesizeDeterministicInvestigation(incident, evidenceList, timelineList);
}

